    public static string ChoiceLabel(string value) =>
        ChoiceNames.TryGetValue(value, out var chinese)
            ? $"{chinese} / {value}"
            : value;

    public static IReadOnlyList<string> FindMissingTranslations(
        IEnumerable<ScrcpyOptionDefinition> options) =>
        options
            .Where(option => !Names.ContainsKey(option.CliName) ||
                             !Descriptions.ContainsKey(option.CliName))
            .Select(option => option.CliName)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(name => name, StringComparer.Ordinal)
            .ToList();
